const assert = require('node:assert/strict');
/** Fast ordinary-startup success guard; no prebuilt container, witness, workforce or stale-request injection. */
function verifyStartupAdmission(memory,rows) {
  const last = rows.at(-1), births = Object.values(memory.pipelineBirths);
  assert.equal(last.probe.staleAt,null); assert.equal(last.stopped,null);
  assert.ok(last.visible && last.lease?.sources === 1);
  const miners = births.filter(birth => birth.family === 'miner');
  assert.equal(miners.length,1); assert.ok(miners[0].activeAt < last.tick);
  assert.ok(births.every(birth => ['distributor','scout','miner'].includes(birth.family)));
  assert.ok(births.every(birth => birth.activeAt !== undefined),'all paid births must become active');
  assert.equal((memory.startupCalls ?? []).filter(call => call.family === 'miner' && call.code === 0).length,1);
  assert.ok(last.probe.construction > 0 && last.probe.construction < 5000);
  assert.ok(!last.probe.sites.some(site => site.complete));
  assert.ok(last.units.some(unit => unit.family === 'miner' && unit.room === 'E0N1' && !unit.spawning && unit.tasks > 0));
  assert.equal(last.miningClaims,1); assert.equal(last.income,0); assert.equal(last.probe.localExpiryEnergy,0);
  const homeCapital = row => row.homeEnergy+row.units.filter(unit => unit.room === 'W0N1').reduce((sum,unit) => sum+unit.cargo,0)+row.birthCost;
  assert.equal(homeCapital(last),homeCapital(rows[0]));
  assert.deepEqual(memory.stampReloads,[21,81,150]);
  const observed = memory.startupFacts;
  assert.equal(observed.status,'observed');
  const facts = observed.facts;
  assert.equal(facts.observedAt,150); assert.equal(facts.home,'W0N1'); assert.equal(facts.room,'E0N1');
  assert.equal(facts.station.facts.status,'building');
  assert.equal(facts.station.facts.progress+facts.station.facts.remainingProgress,5000);
  assert.ok(facts.station.facts.progress > 0 && facts.station.facts.progress <= last.probe.construction);
  assert.equal(facts.stock.totalEnergy,9550); assert.equal(facts.stock.availableEnergy,9550);
  assert.equal(facts.endpoint.type,'storage'); assert.equal(facts.source.capacity,1500);
  assert.ok(facts.source.energy >= 0 && facts.source.energy <= facts.source.capacity);
  assert.equal(facts.workers.length,1); assert.equal(facts.workers[0].spawning,false);
  assert.equal(facts.workers[0].name,Object.entries(memory.pipelineBirths).find(([,birth]) => birth.family === 'miner')[0]);
  assert.ok(facts.authority.generation > 0 && facts.authority.expiresAt > facts.observedAt);
  assert.ok(facts.spawns.length === 1 && facts.spawns[0].remainingTime === 0);
  require('./startup-travel-check.cjs').verifyStartupTravel(memory.startupTravel);
  const continuation = memory.startupTravel.at(-1).projectionContinuation; assert.equal(continuation.status,'ready');
  assert.equal(continuation.input.initial.miner.expiresAt,facts.workers[0].ticksToLive);
  assert.equal(continuation.input.initial.miner.energy,facts.workers[0].energy);
  assert.deepEqual(continuation.input.project.spawning.requests,[]);
  assert.equal(facts.stock.claimedSpawnEnergy,0); assert.equal(facts.stock.availableSpawnEnergy,facts.stock.spawnEnergy);
  const home = memory.startupHomeProof; assert.ok(home);
  assert.equal(home.savedAt,149); assert.equal(home.resumedAt,150); assert.equal(home.format,1); assert.equal(home.through,7);
  assert.equal(home.sources,2); assert.equal(home.trips,2); assert.equal(home.births,1); assert.equal(home.householdCargo,50); assert.equal(home.dueEnergy,36);
  assert.deepEqual(home.result,home.uninterrupted); assert.equal(home.result.spawning.cash.deliveredEnergy,64); assert.equal(home.result.spawning.cash.birthEnergy,100);
  const motion = memory.startupMotionProof; assert.ok(motion);
  assert.equal(motion.savedAt,149); assert.equal(motion.resumedAt,150); assert.equal(motion.format,9); assert.equal(motion.tripCount,1);
  assert.deepEqual(motion.result,motion.uninterrupted); assert.ok(motion.result.delivery.deliveredEnergy > 0);
  const initialMotion = memory.startupInitialMotionProof; assert.ok(initialMotion);
  assert.equal(initialMotion.savedAt,149); assert.equal(initialMotion.resumedAt,150); assert.equal(initialMotion.format,10);
  assert.equal(initialMotion.birthCount,0); assert.equal(initialMotion.tripCount,1);
  assert.deepEqual(initialMotion.result,initialMotion.uninterrupted);
  assert.equal(initialMotion.result.delivery.deliveredEnergy,32); assert.equal(initialMotion.result.delivery.firstDeliveryAt,7);
  assert.equal(initialMotion.result.cash.birthEnergy,0);
  const proof = memory.startupProjectProof; assert.ok(proof);
  assert.equal(proof.savedAt,149); assert.equal(proof.resumedAt,150);
  assert.equal(proof.initialThrough,43); assert.equal(proof.pendingBefore,1);
  assert.equal(proof.recoveredThrough,43); assert.equal(proof.nextThrough,44);
  assert.equal(proof.frames,1); assert.equal(proof.accountedThrough,44);
  assert.ok(proof.checkpointCharacters > 0 && proof.checkpointCharacters < 1048576);
  assert.deepEqual(proof.result,proof.uninterrupted);
  assert.deepEqual(memory.startupLaborProjects.map(proof => proof.kind),['build','upgrade']);
  for (const proof of memory.startupLaborProjects) {
    assert.equal(proof.savedAt,149); assert.equal(proof.resumedAt,150); assert.equal(proof.readOnly,true);
    assert.equal(proof.recoveredThrough,13); assert.equal(proof.through,101); assert.deepEqual(proof.result,proof.uninterrupted);
    assert.equal(proof.result.spawning.labor.jobs[0].spent,proof.kind === 'build' ? 10 : 2);
    const envelope = proof.root.eldrift.records['remoteStartupPlanning/W0N1'];
    assert.equal(envelope.version,7); assert.equal(envelope.data.job.checkpoint.format,7);
    assert.equal(envelope.data.job.checkpoint.household.format,5);
  }
  const historical = memory.startupHistoricalMigration; assert.ok(historical);
  assert.equal(historical.savedAt,149); assert.equal(historical.resumedAt,150); assert.equal(historical.readOnly,true);
  assert.equal(historical.recoveredThrough,21); assert.equal(historical.through,101); assert.equal(historical.status,'complete');
  assert.equal(historical.operationalIsolated,true);
  assert.deepEqual(historical.root,require('../../test/fixtures/startup-historical-upgraded.json'));
  const candidate = memory.startupCandidateMigration; assert.ok(candidate);
  assert.equal(candidate.savedAt,149); assert.equal(candidate.resumedAt,150); assert.equal(candidate.readOnly,true);
  assert.deepEqual(candidate.retained,['compatible']); assert.equal(candidate.version,5); assert.equal(candidate.revision,2);
  assert.equal(candidate.lookup,true); assert.equal(candidate.isolated,true);
  const passive = memory.startupPassiveMigration; assert.ok(passive);
  assert.equal(passive.savedAt,149); assert.equal(passive.resumedAt,150);
  assert.equal(passive.readOnly,true); assert.equal(passive.through,101);
  assert.equal(passive.planningVersion,7); assert.equal(passive.scheduleVersion,4); assert.deepEqual(passive.result,passive.uninterrupted);
  const planning = memory.startupPlanningProof; assert.ok(planning);
  assert.equal(planning.legacyVersion,1); assert.equal(planning.savedAt,149); assert.equal(planning.resumedAt,150);
  assert.equal(planning.initialThrough,43); assert.equal(planning.initialRevision,1); assert.equal(planning.pendingBefore,1);
  assert.equal(planning.recoveredThrough,43); assert.equal(planning.nextThrough,44); assert.equal(planning.nextRevision,2);
  assert.equal(planning.completeThrough,101); assert.equal(planning.completeRevision,3);
  assert.equal(planning.readOnly,true); assert.equal(planning.owner,'remotes'); assert.equal(planning.version,7);
  assert.deepEqual(planning.result,planning.uninterrupted);

}
module.exports = { verifyStartupAdmission };
