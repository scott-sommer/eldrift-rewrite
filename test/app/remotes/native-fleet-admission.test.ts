import { afterEach, expect, test, vi } from 'vitest';
import { managementFixture } from '../../fixtures/remote-management';
import { publishRemoteFleet } from '../../../src/features/remotes/fleet/plan';
import { selectRemotePortfolio } from '../../../src/features/remotes/portfolio';
import { createRemoteFleetStore } from '../../../src/features/remotes/fleet/store';
import { admitRemoteFleetSpawn } from '../../../src/app/remotes/fleet/admission';
import { resolveConfig } from '../../../src/config/resolve';
import { createIntelStore } from '../../../src/features/intel/store';
vi.mock('../../../src/app/remotes/native-route',() => ({ nativeRemoteRoute: () => ({ allowedRooms: ['W0N1','E0N1'] }) }));
vi.mock('../../../src/app/remotes/native-observations',() => ({ createRemoteObservationRefresh: () => () => {} }));
afterEach(() => vi.unstubAllGlobals());
test('final dispatch rejects disabled policy, wrong bodies, expired generations and known foreign extraction targets', () => {
  const f = managementFixture(); f.manager().advance(f.request,{ rooms: 1,sources: 2 },() => true);
  const portfolio = selectRemotePortfolio(f.manager().read().offers,{ ...f.request.policy.portfolio,home: 'W0N1',tick: 20 });
  publishRemoteFleet(f.state,'W0N1',20,f.assignments.read().assignments,portfolio,f.manager().read().offers,100);
  const profile = createRemoteFleetStore(f.state,'W0N1').read().actors[0]!;
  const request = { id: 'request',name: 'name',owner: profile.owner,room: 'W0N1',body: profile.body,priority: 0,readyAt: 20,expiresAt: 100 };
  vi.stubGlobal('Game',{ time: 20,rooms: { W0N1: { controller: { my: true,level: 4,owner: { username: 'bot' } },energyCapacityAvailable: 1300 } } });
  const config = resolveConfig({ empire: { remoteManagementEnabled: true,remoteWorkersEnabled: true,remoteSpawningEnabled: true } },20).values;
  createIntelStore(f.state).observeSummary(f.summary);
  expect(admitRemoteFleetSpawn(f.state,request,() => config)).toBe(true);
  expect(admitRemoteFleetSpawn(f.state,request,() => ({ ...config,remoteSpawningEnabled: false }))).toBe(false);
  expect(admitRemoteFleetSpawn(f.state,request,() => ({ ...config,remoteWorkerMaximumUnits: 0 }))).toBe(false);
  expect(admitRemoteFleetSpawn(f.state,request,() => ({ ...config,remoteMinimumRcl: 5 }))).toBe(false);
  expect(admitRemoteFleetSpawn(f.state,request,() => ({ ...config,remoteMinerBodyBudget: 200 }))).toBe(false);
  expect(admitRemoteFleetSpawn(f.state,{ ...request,body: ['move'] },() => config)).toBe(false);
  createIntelStore(f.state).observeSummary({ ...f.summary,observedAt: 20,controller: { ...f.summary.controller,owner: 'ally' } });
  expect(admitRemoteFleetSpawn(f.state,request,() => config)).toBe(false);
  f.assignments.reconcile({ home: 'W0N1',tick: 20,lifetime: 50,expectedRevision: f.assignments.read().revision,plans: [] });
  expect(admitRemoteFleetSpawn(f.state,request,() => config)).toBe(false);
});
