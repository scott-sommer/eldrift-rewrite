import { afterEach, expect, test, vi } from 'vitest';
import { nativeWorkerSettings } from '../../src/app/native-worker-settings';
import { maintainNativeUpgradeBootstrap } from '../../src/app/native-upgrade-bootstrap-population';
import { isWorkOwner } from '../../src/features/work/identity';
import { upgradeBootstrapOwner, upgradeTarget } from '../../src/features/work/upgrade-identity';
import { defaults } from '../../src/config/model';
import { createSpawnQueue } from '../../src/features/population/spawn-queue';
import type { Envelope } from '../../src/persistence/versioned-state';
afterEach(() => vi.unstubAllGlobals());
test('bootstrap execution is independently enabled and never becomes ordinary demand', () => {
  const owner = upgradeBootstrapOwner('E0N1');
  const config = { ...defaults, upgradeRoomEnabled: true, workersEnabled: false };
  expect(isWorkOwner(owner, 'E0N1')).toBe(false);
  expect(upgradeTarget(owner)).toBe('E0N1');
  expect(nativeWorkerSettings(owner, 'E0N1', config)).toMatchObject({ workersEnabled: true, workerMode: 'builder', workerEnergyStorageReserve: 0 });
  expect(nativeWorkerSettings(owner, 'W0N1', config)).toBeUndefined();
  expect(nativeWorkerSettings('unrelated', 'E0N1', config)).toBeUndefined();
  expect(config.workersEnabled).toBe(false);
});
test('sponsor demand is target scoped, stable, and cancelled when ownership is lost', () => {
  const records = new Map<string, Envelope>();
  const state = { read: (key: string) => records.get(key), write: (key: string, value: Envelope) => { records.set(key, structuredClone(value)); } };
  const room = { controller: { my: true, level: 2, progress: 0, progressTotal: 45000 } };
  vi.stubGlobal('Game', { time: 1, rooms: { E0N1: room } });
  const home = { name: 'W0N1', energyCapacityAvailable: 300 } as Room;
  const config = { ...defaults, upgradeRoomEnabled: true, upgradeRoomSpawningEnabled: true, upgradeFleetTarget: 2 };
  const units = [{ name: 'other', owner: upgradeBootstrapOwner('W1N1'), room: 'W1N1', spawning: false, ticksToLive: 100 }];
  const run = () => maintainNativeUpgradeBootstrap(state, home, 'E0N1', config, true, units, []);
  run();
  const queue = createSpawnQueue(state, home.name);
  const first = queue.list();
  expect(first).toHaveLength(2);
  expect(first[0]).toMatchObject({ room: home.name, home: 'E0N1', owner: upgradeBootstrapOwner('E0N1'), priority: 65 });
  run();
  expect(queue.list()).toEqual(first);
  room.controller.my = false;
  run();
  expect(queue.list()).toEqual([]);
});
